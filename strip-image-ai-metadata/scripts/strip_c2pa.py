def _png_text_fields(chunk_type: bytes, body: bytes):
    """Return (keyword, decoded text) for a PNG text chunk, decompressing zTXt."""
    nul = body.find(b'\x00')
    if nul == -1:
        return '', body.decode('utf-8', errors='ignore')
    keyword = body[:nul].decode('latin-1', errors='ignore')
    rest = body[nul + 1:]
    try:
        if chunk_type == b'tEXt':
            text = rest.decode('latin-1', errors='ignore')
        elif chunk_type == b'zTXt':
            text = zlib.decompress(rest[1:]).decode('utf-8', errors='ignore')
        else:  # iTXt: flag, method, language\0, translated\0, text
            compressed = rest[0] if rest else 0
            tail = rest[2:]
            for _ in range(2):
                cut = tail.find(b'\x00')
                if cut == -1:
                    return keyword, ''
                tail = tail[cut + 1:]
            text = (zlib.decompress(tail) if compressed else tail).decode('utf-8', errors='ignore')
    except (zlib.error, IndexError):
        # Undecodable payload: fall back to the raw bytes so a keyword sitting
        # in there uncompressed is still caught.
        text = rest.decode('latin-1', errors='ignore')
    return keyword, text


def _png_chunk(chunk_type: bytes, body: bytes) -> bytes:
    return (struct.pack('>I', len(body)) + chunk_type + body
            + struct.pack('>I', zlib.crc32(chunk_type + body) & 0xFFFFFFFF))


def strip_png(data: bytes):
    if not data.startswith(PNG_SIG):
        raise ValueError("Not a valid PNG")
    out = bytearray(PNG_SIG)
    idx = 8
    removed = []
    while idx < len(data):
        if idx + 8 > len(data):
            out.extend(data[idx:])
            break
        length = struct.unpack('>I', data[idx:idx+4])[0]
        chunk_type = data[idx+4:idx+8]
        end = idx + 8 + length + 4
        if end > len(data):
            out.extend(data[idx:])
            break
        body = data[idx+8:idx+8+length]
        if chunk_type == b'caBX':
            removed.append(f"caBX ({length} bytes)")
            idx = end
            continue
        # Only textual metadata is eligible for keyword-based removal. Removing
        # an entire eXIf chunk can also remove orientation and thumbnails, so
        # eXIf is scrubbed tag by tag below instead.
        if chunk_type in (b'tEXt', b'iTXt', b'zTXt'):
            keyword, text = _png_text_fields(chunk_type, body)
            if keyword.strip().lower() in PNG_GENERATOR_TEXT_KEYS:
                removed.append(f"{chunk_type.decode()}:{keyword} ({length} bytes)")
                idx = end
                continue
            if _text_has_marker(text) or _text_has_marker(keyword):
                removed.append(f"{chunk_type.decode()}:{keyword or '?'} ({length} bytes)")
                idx = end
                continue
        if chunk_type == b'eXIf':
            scrubbed, hits = _scrub_exif_payload(body)
            if hits:
                removed.append(f"eXIf attribution tags ({', '.join(hits)})")
                out.extend(_png_chunk(chunk_type, scrubbed))
                idx = end
                continue
        out.extend(data[idx:end])
        idx = end
    return bytes(out), removed



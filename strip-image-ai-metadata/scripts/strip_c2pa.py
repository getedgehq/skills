def process_sidecar_file(path: Path, output: Path | None, in_place: bool) -> bool:
    """Clean a sidecar given directly on the command line."""
    raw = path.read_bytes()
    cleaned, removed, error = clean_sidecar_bytes(path, raw)
    if error:
        print(f"FAILED {path}: sidecar could not be parsed: {error}")
        print("  Nothing was written. Inspect or delete this file by hand before publishing.")
        return False
    if not removed:
        print(f"No AI/C2PA metadata found in {path}")
        return True
    out_path = output or (path if in_place else neutral_name(path))
    if output and not out_path.parent.is_dir():
        print(f"Error: output directory does not exist: {out_path.parent}")
        return False
    _atomic_output(out_path, cleaned, stat.S_IMODE(path.stat().st_mode))
    print(f"Cleaned {path} -> {out_path}")
    for item in removed:
        print(f"  Removed: {item}")
    return _report_residue(out_path)


def _report_residue(out_path: Path) -> bool:
    """Scan a written file for leftovers. A leftover is a failure, not a note."""
    remaining = _binary_markers(out_path.read_bytes())
    if not remaining:
        return True
    print(f"  FAILED: {out_path} still contains {remaining}")
    print("  Do not publish this file. Inspect it with `exiftool -a -G1 -u` "
          "and `strings` before use.")
    return False


def process(path: Path, output: Path | None = None, in_place: bool = False) -> bool:
    if path.suffix.lower() in SIDECAR_SUFFIXES:
        return process_sidecar_file(path, output, in_place)

    source_path = path.resolve(strict=True)
    source_state = source_path.stat()
    data = source_path.read_bytes()
    if not _same_file_state(source_state, source_path.stat()):
        print(f"ABORTED {path}: input changed while it was being read")
        return False
    if data.startswith(PNG_SIG):
        cleaned, removed = strip_png(data)
    elif data.startswith(JPEG_SOI):
        cleaned, removed = strip_jpeg(data)
    elif data.startswith(WEBP_SIG):
        cleaned, removed = strip_webp(data)
    else:
        print(f"Unsupported format: {path}")
        return False

    # A clean image next to a sidecar that still names the generator is not a
    # clean result, so sidecars are resolved before anything is reported.
    sidecars = find_sidecars(path)
    sidecar_plans = []
    sidecar_failed = False
    for sidecar in sidecars:
        raw = sidecar.read_bytes()
        sc_clean, sc_removed, sc_error = clean_sidecar_bytes(sidecar, raw)
        if sc_error:
            sidecar_failed = True
            sidecar_plans.append((sidecar, None, [], sc_error))
        else:
            sidecar_plans.append((sidecar, sc_clean, sc_removed, None))

    sidecar_changes = any(p[2] for p in sidecar_plans)
    if not removed and not sidecar_changes and not sidecar_failed:
        suffix = f" (and {len(sidecars)} sidecar file(s))" if sidecars else ""
        print(f"No AI/C2PA metadata found in {path}{suffix}")
        return True

    if removed:
        # Refuse to write anything that is not byte-identical in pixels. Without
        # this an in-place run can destroy the user's only copy of a photo.
        damage = verify_pixels(data, cleaned)
        if damage:
            print(f"ABORTED {path}: {damage}")
            print("  Original left untouched. This is a bug, please report it.")
            return False

    if output:
        out_path = output
    elif in_place:
        out_path = path
    else:
        out_path = neutral_name(path)

    if output and not out_path.parent.is_dir():
        print(f"Error: output directory does not exist: {out_path.parent}")
        return False

    replacing_source = in_place
    if output:
        replacing_source = output.resolve() == source_path

    if replacing_source:
        if removed:
            _atomic_replace(source_path, cleaned, source_state)
        out_path = path
    elif output:
        _atomic_output(out_path, cleaned, stat.S_IMODE(source_state.st_mode))
    else:
        out_path.write_bytes(cleaned)

    if removed:
        print(f"Cleaned {path} -> {out_path}")
        for r in removed:
            print(f"  Removed: {r}")
        print("  Pixels: unchanged (verified)")
    elif replacing_source:
        print(f"{path}: image itself was already clean, sidecars below")
    else:
        print(f"Copied {path} -> {out_path} (image itself was already clean)")

    ok = _report_residue(out_path)

    for sidecar, sc_clean, sc_removed, sc_error in sidecar_plans:
        if sc_error:
            print(f"  FAILED sidecar {sidecar}: could not be parsed: {sc_error}")
            print("  It was left untouched. Inspect or delete it before publishing.")
            ok = False
            continue
        if not sc_removed:
            print(f"  Sidecar {sidecar.name}: checked, no AI metadata")
            continue
        sc_out = sidecar if replacing_source else sidecar_output_name(sidecar, path, out_path)
        _atomic_output(sc_out, sc_clean, stat.S_IMODE(sidecar.stat().st_mode))
        print(f"  Cleaned sidecar {sidecar} -> {sc_out}")
        for item in sc_removed:
            print(f"    Removed: {item}")
        ok = _report_residue(sc_out) and ok
    return ok


def main():
    parser = argparse.ArgumentParser(
        description="Strip C2PA/AI metadata from images and their .xmp/.json sidecars")
    parser.add_argument("paths", nargs="+", help="Image or sidecar file(s) to clean")
    destination = parser.add_mutually_exclusive_group()
    destination.add_argument("-o", "--output", help="Explicit output path (single input only)")
    destination.add_argument("-i", "--in-place", action="store_true",
                             help="Overwrite the original file instead of renaming")
    args = parser.parse_args()

    if args.output and len(args.paths) > 1:
        print("Error: -o/--output can only be used with a single input file")
        sys.exit(1)

    failed = False
    for p in args.paths:
        path = Path(p)
        if not path.is_file():
            print(f"No such file: {p}")
            sys.exit(1)
        if not process(path, Path(args.output) if args.output else None, args.in_place):
            failed = True
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()

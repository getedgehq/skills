def _binary_markers(blob: bytes):
    low = blob.lower()
    return [k.decode() for k in AI_KEYWORDS if k in low]


def _text_has_marker(text: str) -> bool:
    if not text:
        return False
    low = text.lower()
    return any(m in low for m in AI_TEXT_MARKERS)



def _jpeg_segment(data: bytes, idx: int):
    """Return (marker, end, payload) for a length-bearing marker at idx."""
    if idx + 4 > len(data) or data[idx] != 0xFF:
        return None
    marker = data[idx + 1]
    if marker in (0x00, 0x01, 0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
        return None
    length = struct.unpack('>H', data[idx + 2:idx + 4])[0]
    end = idx + 2 + length
    if length < 2 or end > len(data):
        return None
    return marker, end, data[idx + 4:end]


def _jpeg_app11_group(data: bytes, idx: int):
    """Return the contiguous JPEG-XT APP11 group beginning at idx, if any."""
    first = _jpeg_segment(data, idx)
    if first is None or first[0] != 0xEB or len(first[2]) < 8 or first[2][:2] != b'JP':
        return None
    instance = first[2][2:4]
    expected_sequence = struct.unpack('>I', first[2][4:8])[0]
    if expected_sequence != 1:
        return None

    end = idx
    box_data = bytearray()
    count = 0
    while True:
        segment = _jpeg_segment(data, end)
        if segment is None or segment[0] != 0xEB:
            break
        payload = segment[2]
        if len(payload) < 8 or payload[:2] != b'JP' or payload[2:4] != instance:
            break
        sequence = struct.unpack('>I', payload[4:8])[0]
        if sequence != expected_sequence:
            break
        box_data.extend(payload[8:])
        end = segment[1]
        count += 1
        expected_sequence += 1

    is_c2pa = _is_c2pa_jumbf(box_data)
    return end, count, is_c2pa


def _box_at(data: bytes, idx: int, limit: int):
    """Parse one ISO BMFF/JUMBF box without accepting truncated lengths."""
    if idx + 8 > limit:
        return None
    size = struct.unpack('>I', data[idx:idx + 4])[0]
    box_type = data[idx + 4:idx + 8]
    header_size = 8
    if size == 1:
        if idx + 16 > limit:
            return None
        size = struct.unpack('>Q', data[idx + 8:idx + 16])[0]
        header_size = 16
    elif size == 0:
        size = limit - idx
    end = idx + size
    if size < header_size or end > limit:
        return None
    return box_type, idx + header_size, end


def _is_c2pa_jumbf(data: bytes) -> bool:
    """Match the C2PA manifest-store UUID and label in its JUMBF description."""
    outer = _box_at(data, 0, len(data))
    if outer is None or outer[0] != b'jumb':
        return False
    description = _box_at(data, outer[1], outer[2])
    if description is None or description[0] != b'jumd':
        return False
    payload = data[description[1]:description[2]]
    if len(payload) < 17 or payload[:16] != C2PA_JUMBF_UUID:
        return False
    toggles = payload[16]
    if not toggles & 0x02:
        return False
    label_end = payload.find(b'\x00', 17)
    return label_end != -1 and payload[17:label_end] == b'c2pa'


def _clean_jpeg_trailer(trailer: bytes, depth: int):
    """Clean the bytes that follow EOI.

    They are outside the codestream, so no decoder shows them, but a C2PA
    manifest parked there is still read by the platforms this skill exists to
    defeat. An appended image (MPO/MPF) carries pixels, so it is cleaned
    recursively rather than dropped. Anything else that still smells of AI
    provenance after box-level surgery is dropped whole and reported.
    """
    if not trailer:
        return b'', []
    if trailer.startswith(JPEG_SOI) and depth < 4:
        try:
            cleaned, removed = strip_jpeg(trailer, depth + 1)
            return cleaned, [f"appended image: {r}" for r in removed]
        except ValueError:
            pass

    out = bytearray()
    removed = []
    pos = 0
    while pos < len(trailer):
        box = _box_at(trailer, pos, len(trailer))
        if box is None:
            break
        end = box[2]
        chunk = trailer[pos:end]
        if _is_c2pa_jumbf(chunk):
            removed.append(f"post-EOI C2PA manifest ({end - pos} bytes)")
        else:
            markers = _binary_markers(chunk)
            if markers:
                removed.append(
                    f"post-EOI data ({end - pos} bytes, {', '.join(markers)})")
            else:
                out.extend(chunk)
        pos = end

    rest = trailer[pos:]
    if rest:
        markers = _binary_markers(rest)
        if markers:
            removed.append(f"post-EOI trailer ({len(rest)} bytes, {', '.join(markers)})")
        else:
            out.extend(rest)
    return bytes(out), removed


def strip_jpeg(data: bytes, _depth: int = 0):
    if not data.startswith(JPEG_SOI):
        raise ValueError("Not a valid JPEG")
    out = bytearray(JPEG_SOI)
    idx = 2
    removed = []
    in_scan = False
    marker_from_scan = False
    while idx < len(data):
        if in_scan:
            marker_start = data.find(b'\xFF', idx)
            if marker_start == -1:
                out.extend(data[idx:])
                break
            out.extend(data[idx:marker_start])
            marker_code = marker_start
            while marker_code < len(data) and data[marker_code] == 0xFF:
                marker_code += 1
            if marker_code == len(data):
                out.extend(data[marker_start:])
                break
            marker = data[marker_code]
            if marker == 0x00 or 0xD0 <= marker <= 0xD7:
                out.extend(data[marker_start:marker_code + 1])
                idx = marker_code + 1
                continue
            # Any leading 0xFF bytes are fill; the final one prefixes the marker.
            out.extend(data[marker_start:marker_code - 1])
            idx = marker_code - 1
            in_scan = False
            marker_from_scan = True

        # Preserve malformed/out-of-place bytes rather than silently dropping
        # them. This is also the safety net for incomplete JPEGs without EOI.
        if data[idx] != 0xFF:
            out.append(data[idx])
            idx += 1
            continue
        if idx + 1 >= len(data):
            out.extend(data[idx:])
            idx = len(data)
            break
        marker = data[idx+1]
        # 0xFF fill, stuffed 0xFF00, SOI, restart markers, TEM: no length field.
        if marker == 0xFF:
            out.append(data[idx])
            idx += 1
            continue
        if marker in (0x00, 0x01, 0xD8) or 0xD0 <= marker <= 0xD7:
            out.extend(data[idx:idx+2])
            idx += 2
            marker_from_scan = False
            continue
        if marker == 0xD9:
            out.extend(data[idx:idx+2])
            idx += 2
            trailer, trailer_removed = _clean_jpeg_trailer(data[idx:], _depth)
            out.extend(trailer)
            removed.extend(trailer_removed)
            break

        app11_group = _jpeg_app11_group(data, idx) if marker == 0xEB else None
        if app11_group is not None:
            group_end, count, is_c2pa = app11_group
            if is_c2pa:
                removed.append(f"APP11/C2PA ({count} segment{'s' if count != 1 else ''})")
                idx = group_end
                marker_from_scan = False
                continue

        segment = _jpeg_segment(data, idx)
        if segment is None:
            out.extend(data[idx:])
            break
        marker, end, payload = segment
        # XMP APP1 records go whole. Structured EXIF keeps orientation and
        # thumbnails but loses its attribution tags. APP13/APP14 affect
        # presentation and are never keyword-stripped.
        is_xmp = payload.startswith(JPEG_XMP_HEADERS)
        structured_exif = _is_structured_exif(payload)
        is_unstructured_ai_exif = payload.startswith(b'Exif\x00\x00') and not structured_exif
        if marker == 0xE1 and (is_xmp or is_unstructured_ai_exif):
            text = payload.decode('utf-8', errors='ignore')
            if _text_has_marker(text):
                removed.append(f"APP1/AI ({len(payload)} bytes)")
                idx = end
                marker_from_scan = False
                continue
        if marker == 0xE1 and structured_exif:
            scrubbed, hits = _scrub_exif_payload(payload)
            if hits:
                removed.append(f"APP1/EXIF attribution tags ({', '.join(hits)})")
                out.extend(data[idx:idx + 4])
                out.extend(scrubbed)
                idx = end
                marker_from_scan = False
                continue
        out.extend(data[idx:end])
        idx = end
        if marker == 0xDA:
            in_scan = True
        elif marker == 0xDC and marker_from_scan:
            # DNL may interrupt entropy-coded data without ending the scan.
            in_scan = True
        marker_from_scan = False
    return bytes(out), removed



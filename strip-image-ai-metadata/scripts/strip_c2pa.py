def find_sidecars(image_path: Path):
    """Locate .xmp/.json sidecars next to an image, both naming conventions."""
    found = []
    seen = set()
    try:
        image_id = image_path.stat()
        seen.add((image_id.st_dev, image_id.st_ino))
    except OSError:
        pass
    for suffix in SIDECAR_SUFFIXES:
        for variant in (suffix, suffix.upper()):
            for candidate in (image_path.with_name(image_path.name + variant),
                              image_path.with_name(image_path.stem + variant)):
                if not candidate.is_file():
                    continue
                # Identify by inode: on a case-insensitive filesystem the .xmp
                # and .XMP spellings are the same file.
                info = candidate.stat()
                key = (info.st_dev, info.st_ino)
                if key in seen:
                    continue
                seen.add(key)
                found.append(candidate)
    return found


def sidecar_output_name(sidecar: Path, image_in: Path, image_out: Path) -> Path:
    """Map a sidecar onto the cleaned image's name so the pair stays together."""
    if sidecar.name.lower().startswith(image_in.name.lower()):
        return image_out.with_name(image_out.name + sidecar.suffix.lower())
    return image_out.with_name(image_out.stem + sidecar.suffix.lower())


def _qname(tag: str, prefixes: dict) -> str:
    if tag.startswith('{'):
        uri, local = tag[1:].split('}', 1)
        return f"{prefixes.get(uri, uri)}:{local}"
    return tag


def _split_tag(tag: str):
    if tag.startswith('{'):
        uri, local = tag[1:].split('}', 1)
        return uri, local
    return '', tag


def _xmp_name_is_ai(uri: str, local: str) -> bool:
    blob = f"{uri} {local}".lower()
    return any(hint in blob for hint in XMP_AI_NAME_HINTS)


RDF_NS = 'http://www.w3.org/1999/02/22-rdf-syntax-ns#'


def _scrub_xmp_element(elem, removed, prefixes, is_root=False, context=''):
    """Drop AI provenance from an XMP tree. Returns True if elem must be removed.

    `context` names the closest enclosing property so a hit inside an rdf:Alt
    is reported as dc:description/rdf:li rather than a bare rdf:li.
    """
    uri, local = _split_tag(elem.tag)
    label = _qname(elem.tag, prefixes)
    reported = f"{context}/{label}" if context else label
    if not is_root and _xmp_name_is_ai(uri, local):
        removed.append(reported)
        return True

    before = len(removed)
    for key, value in list(elem.attrib.items()):
        key_uri, key_local = _split_tag(key)
        if _xmp_name_is_ai(key_uri, key_local) or _text_has_marker(value):
            del elem.attrib[key]
            removed.append(f"{reported}/@{_qname(key, prefixes)}")

    child_context = context if (is_root or uri == RDF_NS) else label
    had_children = len(elem) > 0
    for child in list(elem):
        if _scrub_xmp_element(child, removed, prefixes, context=child_context):
            elem.remove(child)

    if not is_root and _text_has_marker(elem.text or ''):
        removed.append(reported)
        return True
    # A property element that lost all of its content is now noise: drop it too,
    # but only when it was this pass that emptied it.
    if (not is_root and had_children and len(elem) == 0
            and not (elem.text or '').strip() and len(removed) > before):
        return True
    return False


def strip_xmp_text(text: str):
    """Return (cleaned_xmp, removed_property_names). Raises on unparseable XML."""
    prefixes = {uri: prefix for prefix, uri
                in re.findall(r'xmlns:([A-Za-z_][\w.\-]*)\s*=\s*"([^"]*)"', text)}
    for uri, prefix in prefixes.items():
        try:
            ET.register_namespace(prefix, uri)
        except ValueError:
            pass

    match = re.search(r'<(?!\?|!)([A-Za-z_][\w.\-:]*)', text)
    if not match:
        raise ValueError("no XML element found")
    root_name = match.group(1)
    closing = f"</{root_name}>"
    close_at = text.rfind(closing)
    if close_at == -1:
        raise ValueError(f"unterminated <{root_name}> element")
    head = text[:match.start()]
    body = text[match.start():close_at + len(closing)]
    tail = text[close_at + len(closing):]

    root = ET.fromstring(body)
    removed = []
    _scrub_xmp_element(root, removed, prefixes, is_root=True)
    if not removed:
        return text, []
    return head + ET.tostring(root, encoding='unicode') + tail, removed


def _scrub_json(node, removed, path=''):
    """Return the cleaned node. Records the dotted path of everything dropped."""
    if isinstance(node, dict):
        cleaned = {}
        for key, value in node.items():
            here = f"{path}.{key}" if path else str(key)
            if str(key).strip().lower() in JSON_GENERATOR_KEYS or _text_has_marker(str(key)):
                removed.append(here)
                continue
            if isinstance(value, str) and _text_has_marker(value):
                removed.append(here)
                continue
            cleaned[key] = _scrub_json(value, removed, here)
        return cleaned
    if isinstance(node, list):
        cleaned = []
        for i, value in enumerate(node):
            here = f"{path}[{i}]"
            if isinstance(value, str) and _text_has_marker(value):
                removed.append(here)
                continue
            cleaned.append(_scrub_json(value, removed, here))
        return cleaned
    return node


def strip_json_text(text: str):
    """Return (cleaned_json_text, removed_paths). Raises on unparseable JSON."""
    parsed = json.loads(text)
    removed = []
    cleaned = _scrub_json(parsed, removed)
    if not removed:
        return text, []
    return json.dumps(cleaned, indent=2, ensure_ascii=False) + '\n', removed


def clean_sidecar_bytes(path: Path, raw: bytes):
    """Return (cleaned_bytes, removed, error). error is set when raw is unparseable."""
    try:
        text = raw.decode('utf-8')
    except UnicodeDecodeError:
        text = raw.decode('utf-8', errors='replace')
    suffix = path.suffix.lower()
    try:
        if suffix == '.json':
            cleaned, removed = strip_json_text(text)
        else:
            cleaned, removed = strip_xmp_text(text)
    except Exception as exc:
        markers = _binary_markers(raw)
        return None, [], f"{type(exc).__name__}: {exc}" + (
            f" (file still contains {', '.join(markers)})" if markers else "")
    return cleaned.encode('utf-8'), removed, None



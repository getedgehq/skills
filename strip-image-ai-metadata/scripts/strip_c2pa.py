def scrub_tiff(block: bytearray):
    """Erase AI attribution tag values inside a TIFF block, in place.

    The value bytes are overwritten with zeros so nothing survives for `strings`
    to find, and the entry is left as a valid empty value. Nothing is moved, so
    every other offset in the block stays correct and orientation, colour and
    thumbnail data are untouched. Returns the names of the tags that were hit.
    """
    hits = []
    if len(block) < 8:
        return hits
    if block[:2] == b'II':
        endian = '<'
    elif block[:2] == b'MM':
        endian = '>'
    else:
        return hits
    if struct.unpack(endian + 'H', block[2:4])[0] != 42:
        return hits

    queue = [struct.unpack(endian + 'I', block[4:8])[0]]
    seen = set()
    while queue:
        ifd = queue.pop(0)
        if ifd in seen or ifd < 8 or ifd + 2 > len(block):
            continue
        seen.add(ifd)
        count = struct.unpack(endian + 'H', block[ifd:ifd + 2])[0]
        entries_end = ifd + 2 + count * 12
        if entries_end > len(block):
            continue
        for i in range(count):
            entry = ifd + 2 + i * 12
            tag, typ = struct.unpack(endian + 'HH', block[entry:entry + 4])
            n = struct.unpack(endian + 'I', block[entry + 4:entry + 8])[0]
            size = TIFF_TYPE_SIZES.get(typ, 0) * n
            if tag in EXIF_SUBIFD_TAGS and typ == 4 and n == 1:
                queue.append(struct.unpack(endian + 'I', block[entry + 8:entry + 12])[0])
                continue
            if tag not in EXIF_ATTRIBUTION_TAGS or size == 0:
                continue
            if size <= 4:
                value_at, value_len = entry + 8, size
            else:
                value_at = struct.unpack(endian + 'I', block[entry + 8:entry + 12])[0]
                value_len = size
                if value_at < 8 or value_at + value_len > len(block):
                    continue
            raw = bytes(block[value_at:value_at + value_len])
            text = raw.decode('utf-8', errors='ignore')
            if tag in (0x9C9B, 0x9C9C, 0x9C9D, 0x9C9E, 0x9C9F):
                text = raw.decode('utf-16-le', errors='ignore')
            if not _text_has_marker(text):
                continue
            for j in range(value_at, value_at + value_len):
                block[j] = 0
            # Leave a valid, empty one-byte value that points nowhere.
            struct.pack_into(endian + 'I', block, entry + 4, 1)
            struct.pack_into(endian + 'I', block, entry + 8, 0)
            hits.append(EXIF_ATTRIBUTION_TAGS[tag])
        if entries_end + 4 <= len(block):
            queue.append(struct.unpack(endian + 'I', block[entries_end:entries_end + 4])[0])
    return hits


def _scrub_exif_payload(payload: bytes):
    """Scrub a payload that is a TIFF block, optionally behind an Exif\\0\\0 header."""
    offset = 6 if payload.startswith(b'Exif\x00\x00') else 0
    block = bytearray(payload[offset:])
    hits = scrub_tiff(block)
    if not hits:
        return payload, []
    return payload[:offset] + bytes(block), hits


def _is_structured_exif(payload: bytes) -> bool:
    """Recognize an EXIF/TIFF payload whose orientation and thumbnails matter."""
    if not payload.startswith(b'Exif\x00\x00') or len(payload) < 14:
        return False
    tiff = payload[6:]
    if tiff[:2] == b'II':
        return tiff[2:4] == b'\x2a\x00'
    if tiff[:2] == b'MM':
        return tiff[2:4] == b'\x00\x2a'
    return False


